/**
 * Devuelve el nombre del archivo PNG del icono para una categoría.
 */
function getCategoriaIcono(string $nombre): string
{
    static $mapa = null;
    static $kws  = null;

    // Construir mapa exacto una sola vez
    if ($mapa === null) {
        $mapa = [];
        foreach (CATEGORIAS as $c) {
            $mapa[strtolower(trim($c['nombre']))] = $c['icono'];
        }
    }
    // Obtener keywords una sola vez (con fallback a array vacío si aún no están)
    if ($kws === null) {
        global $CATEGORIAS_KEYWORDS;
        $kws = isset($CATEGORIAS_KEYWORDS) && is_array($CATEGORIAS_KEYWORDS)
            ? $CATEGORIAS_KEYWORDS : [];
    }

    if (trim($nombre) === '') return 'plato-principal.png';

    $key = strtolower(trim($nombre));

    // Nivel 1 — exacto
    if (isset($mapa[$key])) return $mapa[$key];

    // Nivel 2 — fuzzy
    foreach ($kws as $kw => $data) {
        if (str_contains($key, $kw)) return $data['icono'];
    }

    // Nivel 3 — fallback
    return 'plato-principal.png';
}

/**
 * Devuelve el color hex asociado a una categoría.
 */
function getCategoriaColor(string $nombre): string
{
    static $mapa = null;
    static $kws  = null;

    if ($mapa === null) {
        $mapa = [];
        foreach (CATEGORIAS as $c) {
            $mapa[strtolower(trim($c['nombre']))] = $c['color'];
        }
    }
    if ($kws === null) {
        global $CATEGORIAS_KEYWORDS;
        $kws = isset($CATEGORIAS_KEYWORDS) && is_array($CATEGORIAS_KEYWORDS)
            ? $CATEGORIAS_KEYWORDS : [];
    }

    if (trim($nombre) === '') return '#e67e22';

    $key = strtolower(trim($nombre));

    if (isset($mapa[$key])) return $mapa[$key];

    foreach ($kws as $kw => $data) {
        if (str_contains($key, $kw)) return $data['color'];
    }

    return '#7f8c8d';
}

/**
 * Devuelve array completo [nombre, icono, color, bg] para una categoría.
 */
function getCategoriaIconoCompleto(string $nombre): array
{
    static $kws = null;

    if ($kws === null) {
        global $CATEGORIAS_KEYWORDS;
        $kws = isset($CATEGORIAS_KEYWORDS) && is_array($CATEGORIAS_KEYWORDS)
            ? $CATEGORIAS_KEYWORDS : [];
    }

    $key = strtolower(trim($nombre));

    foreach (CATEGORIAS as $c) {
        if (strtolower(trim($c['nombre'])) === $key) return $c;
    }

    foreach ($kws as $kw => $data) {
        if (str_contains($key, $kw)) {
            return [
                'nombre' => $nombre,
                'icono'  => $data['icono'],
                'color'  => $data['color'],
                'bg'     => '#f9f9f9',
            ];
        }
    }

    return [
        'nombre' => $nombre ?: 'Otros',
        'icono'  => 'plato-principal.png',
        'color'  => '#7f8c8d',
        'bg'     => '#f2f3f4',
    ];
}
